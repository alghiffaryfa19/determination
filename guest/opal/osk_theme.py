def atomic_write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + '.tmp')
    temporary.write_text(text)
    temporary.replace(path)


def prepare_runtime(preferences_path):
    runtime = pathlib.Path(os.environ.get('XDG_RUNTIME_DIR', f'/tmp/opal-osk-{os.getuid()}'))
    root = runtime / 'opal-osk-config'
    gtk = root / 'gtk-3.0'
    atomic_write(gtk / 'gtk.css', css_for(read_preferences(preferences_path)))
    source_config = pathlib.Path(os.environ.get('XDG_CONFIG_HOME', pathlib.Path.home() / '.config'))
    source_settings = source_config / 'gtk-3.0' / 'settings.ini'
    target_settings = gtk / 'settings.ini'
    if source_settings.is_file() and not target_settings.exists():
        target_settings.symlink_to(source_settings)
    source_dconf = source_config / 'dconf'
    target_dconf = root / 'dconf'
    if source_dconf.exists() and not target_dconf.exists():
        target_dconf.symlink_to(source_dconf, target_is_directory=True)
    return root


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--preferences', required=True)
    parser.add_argument('command', nargs=argparse.REMAINDER)
    arguments = parser.parse_args()
    command = arguments.command
    if command and command[0] == '--':
        command = command[1:]
    if not command:
        command = ['squeekboard']
    executable = shutil.which(command[0])
    if not executable:
        raise SystemExit(f'{command[0]} is not installed')
    environment = os.environ.copy()
    environment['XDG_CONFIG_HOME'] = str(prepare_runtime(arguments.preferences))
    environment['GTK_THEME'] = 'Adwaita'
    os.execvpe(executable, [executable, *command[1:]], environment)


if __name__ == '__main__':
    main()
