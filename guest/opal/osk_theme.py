def read_preferences(path):
    try:
        data = json.loads(pathlib.Path(path).read_text())
        return data if isinstance(data, dict) else {}
    except (OSError, ValueError, TypeError):
        return {}


def palette(preferences):
    light = bool(preferences.get('light'))
    fallback = DEFAULT_LIGHT if light else DEFAULT_DARK
    generated = preferences.get('dynamicPalette') if preferences.get('dynamicColors') else None
    generated = generated.get('light' if light else 'dark', {}) if isinstance(generated, dict) else {}
    if not isinstance(generated, dict):
        generated = {}
    return {key: str(generated.get(key, value)) for key, value in fallback.items()}


